"""Generate src/lcd_map.h from a BrickEmuPy Digimon face SVG.

Usage: python gen_lcd_map.py <DigimonV1.svg> <out lcd_map.h>

In BrickEmuPy face SVGs every LCD segment is an element with id
"<vram index>_<bit>". Digimon Ver.1-3 share one layout: a 32x16 dot matrix
plus 8 menu icons (4 above, 4 below the matrix).
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()

pixels = []  # (x, y, byte, bit)
icons = []  # (x, y, byte, bit)
for m in re.finditer(r'<(\w+)\s([^>]*?)id="(\d+)_(\d)"([^>]*)>', src):
    tag, a1, byte, bit, a2 = m.groups()
    byte, bit = int(byte), int(bit)
    if tag == "path" and "fill-rule" not in a1 + a2:
        d = re.search(r'\sd="([^"]*)"', " " + a1 + a2).group(1)
        vals = list(map(float, re.findall(r"-?\d*\.?\d+", d)))
        xs, ys = vals[0::2], vals[1::2]
        if round(max(xs) - min(xs)) == 36 and round(max(ys) - min(ys)) == 36:
            pixels.append((min(xs), min(ys), byte, bit))
            continue
    # icon: position = first coordinate found inside the element
    chunk = src[m.start() : m.start() + 600]
    xy = re.search(r'd="M\s*(-?\d+\.?\d*)[ ,](-?\d+\.?\d*)', chunk)
    icons.append((float(xy.group(1)), float(xy.group(2)), byte, bit))


def clusters(values):
    out = []
    for v in sorted(set(round(v) for v in values)):
        if out and v - out[-1][-1] < 10:
            out[-1].append(v)
        else:
            out.append([v])
    return [sum(c) / len(c) for c in out]


cols = clusters(p[0] for p in pixels)
rows = clusters(p[1] for p in pixels)
assert len(cols) == 32 and len(rows) == 16, (len(cols), len(rows))
grid = [[None] * 32 for _ in range(16)]
for x, y, byte, bit in pixels:
    c = min(range(32), key=lambda i: abs(cols[i] - x))
    r = min(range(16), key=lambda i: abs(rows[i] - y))
    assert grid[r][c] is None
    grid[r][c] = (byte << 2) | bit

assert len(icons) == 8, len(icons)
mid_y = (rows[0] + rows[-1]) / 2
top = sorted([i for i in icons if i[1] < mid_y])
bottom = sorted([i for i in icons if i[1] >= mid_y])
assert len(top) == 4 and len(bottom) == 4

with open(sys.argv[2], "w", newline="\n") as out:
    out.write("/* Generated by tools/gen_lcd_map.py - do not edit. */\n")
    out.write("#pragma once\n\n#include <stdint.h>\n\n")
    out.write("#define LCD_W 32\n#define LCD_H 16\n#define LCD_ICONS 8\n\n")
    out.write("/* (vram index << 2) | bit for every dot of the 32x16 matrix */\n")
    out.write("static const uint16_t lcd_map[LCD_H][LCD_W] = {\n")
    for r in grid:
        out.write("    {" + ", ".join("0x%03X" % v for v in r) + "},\n")
    out.write("};\n\n")
    out.write("/* Menu icons: top row left to right, then bottom row left to right */\n")
    out.write("static const uint16_t lcd_icon_map[LCD_ICONS] = {\n")
    out.write("    " + ", ".join("0x%03X" % ((b << 2) | bit) for _, _, b, bit in top + bottom))
    out.write(",\n};\n")
print("ok", len(pixels), "pixels")
